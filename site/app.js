/* LottoShark front end. Data arrives as window.LOTTO[code] from site/data/<code>.js,
   generated by build.py. Plain DOM; filter, sort, render, expand a row. */
(function () {
  "use strict";

  const $ = (id) => document.getElementById(id);
  const els = {
    state: $("state"), q: $("q"), price: $("price"), offsale: $("offsale"), rows: $("rows"),
    empty: $("empty"), status: $("status"), sources: $("sources"), table: $("games"),
  };
  const state = { code: null, q: "", price: "", offsale: false, sort: "current_return", dir: "desc", open: null };

  // ---- formatting
  const money = (n, d = 2) => "$" + Number(n).toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d });
  const int = (n) => Number(n).toLocaleString("en-US");
  const signedCents = (r) => { const c = Math.round(r * 100); return (c > 0 ? "+" : c < 0 ? "−" : "") + Math.abs(c) + "¢"; };
  const oneIn = (x) => (x ? "1 in " + (x >= 100 ? int(Math.round(x)) : Number(x).toFixed(2)) : "—");
  const priceLabel = (p) => (p ? "$" + (Number.isInteger(p) ? p : p.toFixed(2)) : "—");
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const dateFmt = (iso) => {
    if (!iso) return "";
    const [y, m, d] = iso.split("-").map(Number);
    return new Date(y, m - 1, d).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
  };

  const data = () => window.LOTTO[state.code];
  const onSale = (g) => g.price > 0 && !g.notes.some((n) => /off sale|deadline/.test(n));
  const jackpotDriven = (m) => m && m.current_return - m.current_return_ex_top > 0.15;
  const rangeText = (lo, hi) => (hi - lo < 0.005 ? "" : `${money(lo)}–${money(hi)}`);

  // ---- setup
  // index.js lists {code, name} for every state with data; each state's file is loaded on
  // demand so the page does not download 40 states' worth of games to show one.
  const STATES = window.LOTTO_STATES || [];
  const loaded = {};
  function loadState(code) {
    if (loaded[code]) return loaded[code];
    loaded[code] = loadScript(`data/${code.toLowerCase()}.js`).then(() => !!(window.LOTTO && window.LOTTO[code]));
    return loaded[code];
  }

  function loadStates() {
    const codes = STATES.map((s) => (typeof s === "string" ? s : s.code));
    if (!codes.length) {
      els.state.innerHTML = "<option>None</option>";
      els.empty.hidden = false;
      els.empty.textContent = "No data found. Run python build.py, then reload.";
      return false;
    }
    els.state.innerHTML = STATES.map((s) => typeof s === "string"
      ? `<option value="${s}">${esc(s)}</option>`
      : `<option value="${esc(s.code)}">${esc(s.name)}</option>`).join("");
    const fromHash = (location.hash.match(/#([A-Za-z]{2})(?:[/=]|$)/) || [])[1];
    const saved = safeGet("state");
    state.code = codes.includes((fromHash || "").toUpperCase()) ? fromHash.toUpperCase() : codes.includes(saved) ? saved : codes[0];
    els.state.value = state.code;
    return true;
  }

  function fillPrices() {
    const prices = [...new Set(data().games.filter((g) => g.price > 0).map((g) => g.price))].sort((a, b) => a - b);
    els.price.innerHTML = `<option value="">Any</option>` + prices.map((p) => `<option value="${p}">${priceLabel(p)}</option>`).join("");
    els.price.value = "";
    state.price = "";
  }

  function renderStatus(shown) {
    const d = data();
    const live = d.games.filter((g) => g.metrics && onSale(g));
    const avg = live.length ? live.reduce((s, g) => s + g.metrics.current_return, 0) / live.length : 0;
    const above = live.filter((g) => g.metrics.current_return >= 1).length;
    const when = new Date(d.fetched_at);
    const stale = Date.now() - when.getTime() > 36 * 3600 * 1000;
    els.status.textContent = (stale ? "Stale data: the last successful fetch for this state was " + when.toLocaleDateString("en-US", { month: "short", day: "numeric" }) + ". " : "") +
      `${d.name}: ${live.length} games on sale, ${shown} shown. Average return ${Math.round(avg * 100)}¢ per $1; ` +
      `${above === 0 ? "none are" : above === 1 ? "1 game is" : above + " games are"} at or above $1.00. ` +
      `Data from the state as of ${when.toLocaleDateString("en-US", { month: "short", day: "numeric" })}, ${when.toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit" })}.`;
    els.sources.innerHTML = "Sources: " + d.sources.map((s) => `<a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.label)}</a>`).join("; ") + ".";
  }

  // ---- filter + sort
  function sortValue(g, key) {
    if (key === "name") return g.name;
    if (key === "price") return g.price;
    if (key === "top_prize_remaining") return g.top_prize_remaining;
    if (!g.metrics) return null;
    return g.metrics[key];
  }

  function visibleGames() {
    const q = state.q.trim().toLowerCase();
    const list = data().games.filter((g) => {
      if (!state.offsale && !onSale(g)) return false;
      if (state.price !== "" && g.price !== Number(state.price)) return false;
      if (q && !(g.name.toLowerCase().includes(q) || g.game_number.includes(q))) return false;
      return true;
    });
    const mul = state.dir === "desc" ? -1 : 1;
    list.sort((a, b) => {
      const va = sortValue(a, state.sort), vb = sortValue(b, state.sort);
      if (va == null && vb == null) return 0;
      if (va == null) return 1;            // games without metrics always sink
      if (vb == null) return -1;
      if (typeof va === "string") return mul * va.localeCompare(vb);
      if (va === vb) return (b.metrics?.current_return ?? -1) - (a.metrics?.current_return ?? -1);
      return mul * (va - vb);
    });
    return list;
  }

  // ---- render
  // Logos ship with the site (site/logos/, fetched by build.py); fall back to the state's
  // own image URL, and to nothing at all if neither loads.
  function logoHtml(g) {
    const src = g.logo || g.image;
    if (!src) return `<span class="logo logo-empty"></span>`;
    return `<img class="logo" src="${esc(src)}" alt="" loading="lazy" onerror="this.className='logo logo-empty';this.removeAttribute('src')">`;
  }

  function rowHtml(g, i) {
    const m = g.metrics, off = !onSale(g);
    const ret = m
      ? `<span class="${m.current_return >= 1 ? "strong up" : ""}">${money(m.current_return)}</span>${jackpotDriven(m) ? `<span class="dag">†</span>` : ""}${m.estimated && rangeText(m.return_low, m.return_high) ? `<span class="range">${rangeText(m.return_low, m.return_high)}</span>` : ""}`
      : `<span class="meta">n/a</span>`;
    const edge = m && m.edge != null ? `<span class="${m.edge > 0.02 ? "up" : m.edge < -0.02 ? "down" : ""}">${signedCents(m.edge)}</span>` : "";
    const topLeft = g.tiers[0] ? `${g.tiers[0].unpaid == null ? "?" : int(g.top_prize_remaining)} of ${int(g.tiers[0].total)}` : int(g.top_prize_remaining);
    return `<tr class="row" data-game="${esc(g.game_number)}" tabindex="0" aria-expanded="${state.open === g.game_number}">
      <td class="c-rank">${i + 1}</td>
      <td class="c-game"><div class="game-cell">${logoHtml(g)}<div><div class="name">${esc(g.name)}${off ? ` <span class="off">(off sale)</span>` : ""}</div><div class="meta">#${esc(g.game_number)} · ${priceLabel(g.price)}${g.top_prize_label ? " · top " + esc(g.top_prize_label) : ""}</div></div></div></td>
      <td class="c-price num">${priceLabel(g.price)}</td>
      <td class="c-ret num">${ret}</td>
      <td class="c-extop num">${m ? money(m.current_return_ex_top) + (m.estimated && rangeText(m.return_ex_top_low, m.return_ex_top_high) ? `<span class="range">${rangeText(m.return_ex_top_low, m.return_ex_top_high)}</span>` : "") : ""}</td>
      <td class="c-edge num">${edge}</td>
      <td class="c-sold num">${m && m.pct_sold != null ? m.pct_sold.toFixed(0) + "%" + (m.estimated && m.pct_sold_high - m.pct_sold_low >= 1 ? `<span class="range">${m.pct_sold_low.toFixed(0)}–${m.pct_sold_high.toFixed(0)}%</span>` : "") : ""}</td>
      <td class="c-top num">${topLeft}</td>
      <td class="c-odds num">${m ? oneIn(m.odds_any_now) : ""}</td>
    </tr>`;
  }

  function verdict(g) {
    const m = g.metrics;
    if (!m) return "The state has not published prize-level counts for this game yet, so there is no estimate.";
    const cmp = m.edge > 0.02 ? "better than" : m.edge < -0.02 ? "worse than" : "about the same as";
    let s = m.remaining_only
      ? `A ticket bought today returns about ${money(m.current_return)} per $1 on average. The state publishes remaining counts for every prize but not how many were printed, so tickets unsold are taken as prizes unclaimed times the overall odds.${m.current_return >= 1 ? " The unclaimed prizes are worth more than the unsold tickets." : ""}`
      : m.launch_return == null
      ? `A ticket bought today returns about ${money(m.current_return)} per $1 on average, from the state's own figures for prize money unclaimed and tickets sold.${m.current_return >= 1 ? " The unclaimed prizes are worth more than the unsold tickets." : ""}`
      : m.current_return >= 1
      ? `The unclaimed prizes are currently worth more than the unsold tickets: about ${money(m.current_return)} back per $1, against ${money(m.launch_return)} when the game launched.`
      : `A ticket bought today returns about ${money(m.current_return)} per $1 on average, ${cmp} the ${money(m.launch_return)} it returned at launch.`;
    s += jackpotDriven(m)
      ? ` Most of that is the ${esc(g.top_prize_label || "top prize")}; leave it out and the figure is ${money(m.current_return_ex_top)}.`
      : ` Leaving out the top prize, it is ${money(m.current_return_ex_top)}.`;
    if (g.top_prize_remaining === 0 && g.tiers[0] && g.tiers[0].unpaid != null) s += " Every top prize has already been claimed and tickets are still being sold.";
    if (m.aggregate) {
      s += ` The state rounds its percent-sold figure, so the return is between ${money(m.return_low)} and ${money(m.return_high)}.`;
    } else if (m.estimated) {
      s += m.unknown_tiers
        ? ` The state publishes remaining counts only for ${m.unknown_tiers === g.tiers.length ? "no" : "the top"} prize levels here, so the share of tickets sold is inferred from those ${m.published_prizes != null ? int(m.published_prizes) + " prizes" : "figures"}; there is a 90% chance the true return is between ${money(m.return_low)} and ${money(m.return_high)}.`
        : ` This is estimated from limited figures; there is a 90% chance the true return is between ${money(m.return_low)} and ${money(m.return_high)}.`;
    }
    return s;
  }

  function detailHtml(g) {
    const m = g.metrics;
    const facts = m ? `<dl class="facts">
        <dt>Ticket price</dt><dd>${priceLabel(g.price)}</dd>
        <dt>Odds on ticket</dt><dd>${esc(g.odds_label || "—")}</dd>
        ${m.odds_any_now != null ? `<dt>Any prize, now</dt><dd>${oneIn(m.odds_any_now)}</dd>` : ""}
        ${m.top_prize_odds_now != null ? `<dt>Top prize, now</dt><dd>${oneIn(m.top_prize_odds_now)} (${int(g.top_prize_remaining)} left)</dd>` : ""}
        ${m.total_tickets != null ? `<dt>Tickets printed</dt><dd>${int(m.total_tickets)}${m.aggregate ? "" : " (est.)"}</dd>` : ""}
        <dt>Tickets unsold</dt><dd>${int(m.tickets_remaining)}${m.pct_sold != null ? `, ${(100 - m.pct_sold).toFixed(1)}%` : ""} (est.)</dd>
        <dt>Prize money unclaimed</dt><dd>${money(m.remaining_prize_money, 0)}${m.estimated ? " (est.)" : ""}</dd>
        ${m.estimated ? `<dt>Return now, 90% range</dt><dd>${money(m.return_low)} to ${money(m.return_high)} / $1</dd>` : ""}
        ${m.launch_return != null ? `<dt>Return at launch</dt><dd>${money(m.launch_return)} / $1 (${money(m.launch_return_ex_top)} without top prize)</dd>` : ""}
        ${g.release_date ? `<dt>Released</dt><dd>${dateFmt(g.release_date)}</dd>` : ""}
        ${g.end_date ? `<dt>Claim deadline</dt><dd>${dateFmt(g.end_date)}</dd>` : ""}
      </dl>` : "<div></div>";
    const annuity = g.tiers.some((t) => t.annuity);
    const tiers = g.tiers.length ? `<table class="tiers">
        <thead><tr><th>Prize</th><th>Printed</th><th>Unclaimed</th><th>Left</th></tr></thead>
        <tbody>${g.tiers.map((t) => t.unpaid == null
          ? `<tr class="est"><td>${esc(t.label)}${t.annuity ? "*" : ""}</td><td>${int(t.total)}</td><td>${t.unpaid_est != null ? "~" + int(t.unpaid_est) : "—"}</td><td>${t.unpaid_est != null && t.total ? "~" + (100 * t.unpaid_est / t.total).toFixed(0) + "%" : ""}</td></tr>`
          : `<tr><td>${esc(t.label)}${t.annuity ? "*" : ""}</td><td>${t.total ? int(t.total) : "—"}</td><td>${int(t.unpaid)}</td><td>${t.total ? (100 * t.unpaid / t.total).toFixed(1) + "%" : ""}</td></tr>`).join("")}</tbody>
        ${annuity || g.tiers.some((t) => t.unpaid == null) ? `<tfoot><tr><td colspan="4">${annuity ? "* Annuity, counted at its undiscounted total; for-life prizes at 20 years. " : ""}${g.tiers.some((t) => t.unpaid == null) ? "~ Not published by the state; estimated from the share of tickets sold." : ""}</td></tr></tfoot>` : ""}
      </table>` : "";
    const notes = g.notes.map((n) => `<p class="note">${esc(n)}</p>`).join("");
    const links = `<div class="links"><a href="${esc(g.url)}" target="_blank" rel="noopener">Official game page</a>${g.pdf ? `<a href="${esc(g.pdf)}" target="_blank" rel="noopener">Official odds sheet (PDF)</a>` : ""}<a href="#${esc(state.code)}/game=${esc(g.game_number)}">Link to this game</a></div>`;
    const art = g.image ? `<img class="art" src="${esc(g.logo || g.image)}" alt="${esc(g.name)} ticket" loading="lazy" onerror="this.remove()">` : "";
    return `<tr class="detail" data-detail="${esc(g.game_number)}"><td colspan="9"><div class="detail-inner">
      <p class="verdict">${verdict(g)}</p>${facts}${tiers}${notes}${links}${art}
    </div></td></tr>`;
  }

  function render() {
    const list = visibleGames();
    els.empty.hidden = list.length > 0;
    els.rows.innerHTML = list.map((g, i) => rowHtml(g, i) + (state.open === g.game_number ? detailHtml(g) : "")).join("");
    renderStatus(list.length);
    els.table.querySelectorAll("th[data-sort]").forEach((th) => {
      if (th.dataset.sort === state.sort) th.setAttribute("aria-sort", state.dir === "desc" ? "descending" : "ascending");
      else th.removeAttribute("aria-sort");
    });
  }

  function toggle(num) {
    state.open = state.open === num ? null : num;
    if (history.replaceState) history.replaceState(null, "", state.open ? `#${state.code}/game=${state.open}` : `#${state.code}`);
    render();
    const row = els.rows.querySelector(`tr.row[data-game="${num}"]`);
    if (row) row.focus({ preventScroll: true });
  }
  window.addEventListener("hashchange", () => {
    const h = location.hash.match(/game=([\w-]+)/);
    if (h && state.code && h[1] !== state.open && data().games.some((g) => g.game_number === h[1])) toggle(h[1]);
  });

  // ---- storage: remembered state only
  function safeGet(k) { try { return localStorage.getItem("lottoshark:" + k); } catch { return null; } }
  function safeSet(k, v) { try { localStorage.setItem("lottoshark:" + k, v); } catch { /* ignore */ } }

  // ---- events
  els.state.addEventListener("change", () => {
    const code = els.state.value;
    els.status.textContent = "Loading…";
    loadState(code).then((ok) => {
      if (!ok) { els.status.textContent = `No data for ${code}.`; els.state.value = state.code; return; }
      state.code = code; safeSet("state", code); state.open = null;
      if (history.replaceState) history.replaceState(null, "", `#${code}`);
      fillPrices(); render();
    });
  });
  els.q.addEventListener("input", () => { state.q = els.q.value; render(); });
  els.price.addEventListener("change", () => { state.price = els.price.value; render(); });
  els.offsale.addEventListener("change", () => { state.offsale = els.offsale.checked; render(); });
  els.table.querySelector("thead").addEventListener("click", (e) => {
    const th = e.target.closest("th[data-sort]"); if (!th) return;
    const key = th.dataset.sort;
    if (state.sort === key) state.dir = state.dir === "desc" ? "asc" : "desc";
    else { state.sort = key; state.dir = key === "name" ? "asc" : "desc"; }
    render();
  });
  els.rows.addEventListener("click", (e) => {
    if (e.target.closest("a")) return;
    const tr = e.target.closest("tr.row"); if (tr) toggle(tr.dataset.game);
  });
  els.rows.addEventListener("keydown", (e) => {
    if (e.key !== "Enter" && e.key !== " ") return;
    const tr = e.target.closest("tr.row"); if (tr) { e.preventDefault(); toggle(tr.dataset.game); }
  });

  // ---- boot: load each state's data file, then render
  function loadScript(src) {
    return new Promise((resolve) => { const s = document.createElement("script"); s.src = src; s.onload = resolve; s.onerror = resolve; document.head.appendChild(s); });
  }
  if (!loadStates()) return;
  loadState(state.code).then((ok) => {
    if (!ok) { els.status.textContent = `No data for ${state.code}.`; return; }
    fillPrices();
    const h = location.hash.match(/game=([\w-]+)/);
    if (h && data().games.some((g) => g.game_number === h[1])) {
      state.open = h[1];
      const g = data().games.find((x) => x.game_number === h[1]);
      if (!onSale(g)) { state.offsale = true; els.offsale.checked = true; }
    }
    render();
    if (state.open) { const row = els.rows.querySelector(`tr.row[data-game="${state.open}"]`); if (row) row.scrollIntoView({ block: "start" }); }
  });
})();
